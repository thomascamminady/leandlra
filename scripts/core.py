"""The core library and the catalogue: which module is where, and the rule between them.

The repository holds two libraries over the same source tree (``docs/STRUCTURE.md``):

* the core library ``LeanDLRA``: the modules imported by ``LeanDLRA.lean``;
* the catalogue: every other module below ``LeanDLRA/``; ``LeanDLRACatalogue.lean`` imports the core
  and the catalogue.

Both root files are generated by ``scripts/gen_root.sh``. The rule checked here: a core module
imports no catalogue module. Then ``lake build LeanDLRA`` compiles exactly the modules listed in
``LeanDLRA.lean``, and a change of the core never has to wait for the catalogue.

Usage::

    uv run -q scripts/core.py check       # exit status 1 if a core module imports the catalogue
    uv run -q scripts/core.py modules     # the core modules, one per line
    uv run -q scripts/core.py summary     # numbers of modules and lines in both parts
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = "LeanDLRA"
CORE_ROOT = "LeanDLRA.lean"
IMPORT = re.compile(r"(?:public\s+|private\s+|meta\s+)*import\s+(?:all\s+)?(\S+)")


def header_imports(text: str) -> list[str]:
    """The modules imported by a Lean source text.

    Imports stand before every other command, so the scan stops at the first token that is neither
    a comment, nor ``module``, nor an import. A line that starts with ``import`` inside a later
    comment or string is therefore not read as an import.
    """
    imports: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        if text[i].isspace():
            i += 1
        elif text.startswith("--", i):
            end = text.find("\n", i)
            i = n if end < 0 else end + 1
        elif text.startswith("/-", i):
            depth = 1
            i += 2
            while i < n and depth > 0:
                if text.startswith("/-", i):
                    depth += 1
                    i += 2
                elif text.startswith("-/", i):
                    depth -= 1
                    i += 2
                else:
                    i += 1
        else:
            end = text.find("\n", i)
            line = text[i : n if end < 0 else end].strip()
            match = IMPORT.fullmatch(line)
            if match:
                imports.append(match.group(1))
            elif line != "module":
                break
            i = n if end < 0 else end + 1
    return imports


def source_of(module: str, root: Path = ROOT) -> Path:
    """The source file of a module."""
    return root.joinpath(*module.split(".")).with_suffix(".lean")


def core_modules(root: Path = ROOT) -> list[str]:
    """The modules listed in ``LeanDLRA.lean``."""
    return header_imports((root / CORE_ROOT).read_text(encoding="utf-8"))


def all_modules(root: Path = ROOT) -> list[str]:
    """Every module with a source file below ``LeanDLRA/``."""
    return sorted(
        ".".join(p.relative_to(root).with_suffix("").parts)
        for p in (root / PACKAGE).rglob("*.lean")
    )


def violations(root: Path = ROOT) -> list[tuple[str, str]]:
    """Pairs (core module, imported module of this package that is not core)."""
    core = core_modules(root)
    listed = set(core)
    found: list[tuple[str, str]] = []
    for module in core:
        text = source_of(module, root).read_text(encoding="utf-8")
        found += [
            (module, dep)
            for dep in header_imports(text)
            if dep.startswith(PACKAGE + ".") and dep not in listed
        ]
    return found


def check() -> None:
    """Exit with status 1 if a core module imports a module that is not core."""
    bad = violations()
    if bad:
        for module, dep in bad:
            print(f"core module {module} imports catalogue module {dep}")
        print(
            f"{len(bad)} import(s) leave the core: remove the import, or add the imported "
            "module to docs/promoted.txt and run scripts/gen_root.sh"
        )
        sys.exit(1)
    print(f"core OK: {len(core_modules())} modules, no import of a catalogue module")


def modules() -> None:
    """Print the core modules, one per line."""
    print("\n".join(core_modules()))


def summary() -> None:
    """Print the numbers of modules and source lines of the core and of the catalogue."""

    def lines(names: list[str]) -> int:
        return sum(source_of(m).read_text(encoding="utf-8").count("\n") for m in names)

    core = core_modules()
    rest = sorted(set(all_modules()) - set(core))
    total = lines(core) + lines(rest)
    for label, names in (("core", core), ("catalogue", rest)):
        share = 100 * lines(names) / total if total else 0.0
        print(
            f"{label:9s} {len(names):4d} modules {lines(names):7d} lines ({share:.1f} %)"
        )


def cli() -> None:
    """Command line."""
    import fire  # imported here so that the tests need only pytest

    fire.Fire({"check": check, "modules": modules, "summary": summary})


if __name__ == "__main__":
    cli()
