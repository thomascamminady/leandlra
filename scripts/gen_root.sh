#!/usr/bin/env bash
# Regenerate the two root files from the tracked sources (docs/STRUCTURE.md).
#
#   LeanDLRA.lean            the core library: every module outside the catalogue folders, plus the
#                            catalogue modules listed in docs/promoted.txt
#   LeanDLRACatalogue.lean   everything: `import LeanDLRA` plus all remaining modules
#
# `lake build LeanDLRA` builds the core, `lake build LeanDLRACatalogue` builds everything.
# CI runs this script before building and compares the result with the committed root files.
set -euo pipefail
cd "$(dirname "$0")/.."
export LC_ALL=C
# Folders of the catalogue: paper-by-paper material that is not (yet) stated in the core definitions.
catalogue='^LeanDLRA\.(Literature|OpenProblems|Novel|Corrections)\.'
promoted_file=docs/promoted.txt

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
git ls-files 'LeanDLRA/*.lean' 'LeanDLRA/**/*.lean' | sed 's|\.lean$||; s|/|.|g' | sort -u > "$tmp/all"
if [ -f "$promoted_file" ]; then
  { grep -v -E '^[[:space:]]*(#|$)' "$promoted_file" || true; } | awk '{print $1}' | sort -u > "$tmp/promoted"
else
  : > "$tmp/promoted"
fi
unknown=$(comm -23 "$tmp/promoted" "$tmp/all")
if [ -n "$unknown" ]; then
  echo "gen_root: $promoted_file names modules that are not tracked source files:" >&2
  echo "$unknown" >&2
  exit 1
fi
{ grep -v -E "$catalogue" "$tmp/all" || true; cat "$tmp/promoted"; } | sort -u > "$tmp/core"
comm -23 "$tmp/all" "$tmp/core" > "$tmp/rest"

{
  echo "-- Generated by scripts/gen_root.sh: the core library (every module outside the catalogue"
  echo "-- folders, plus the modules of docs/promoted.txt)."
  sed 's|^|import |' "$tmp/core"
} > "$tmp/LeanDLRA.lean"
{
  echo "-- Generated by scripts/gen_root.sh: everything, that is, the core library and the catalogue."
  echo "import LeanDLRA"
  sed 's|^|import |' "$tmp/rest"
} > "$tmp/LeanDLRACatalogue.lean"
for root in LeanDLRA.lean LeanDLRACatalogue.lean; do
  cmp -s "$tmp/$root" "$root" || cp "$tmp/$root" "$root"
done
